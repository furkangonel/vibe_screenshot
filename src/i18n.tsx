export function translate(language: Language, key: string) {
  return messages[key]?.[language === 'en' ? 0 : 1] ?? key;
}
const Context = createContext({
  language: 'en' as Language,
  setLanguage: (_: Language) => {},
  t: (key: string) => key,
});
export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setLanguage] = useState<Language>(() => {
    const saved = readPreference('language');
    return saved === 'tr' || saved === 'en' ? saved : navigator.language.startsWith('tr') ? 'tr' : 'en';
  });
  useEffect(() => {
    document.documentElement.lang = language;
    writePreference('language', language);
  }, [language]);
  return (
    <Context.Provider value={{ language, setLanguage, t: (key) => translate(language, key) }}>
      {children}
    </Context.Provider>
  );
}
export function useI18n() {
  return useContext(Context);
}
